import { useMemo, useState } from "react";
import { useNavigate, useParams } from "react-router-dom";
import { FileText } from "lucide-react";
import { Card, PageHeader } from "@/components/common/Card";
import { EmptyState, ErrorState } from "@/components/common/EmptyState";
import { SearchInput } from "@/components/common/SearchInput";
import { TableSkeleton } from "@/components/common/Skeleton";
import { DocumentListItem } from "@/components/documents/DocumentListItem";
import { DocumentPane } from "@/components/documents/DocumentPane";
import { useWorkspace } from "@/hooks/useWorkspace";
import { statusLabel } from "@/lib/status";

const APPROVAL_STATUSES = ["PENDING", "APPROVED", "REJECTED"];

export default function DocumentsPage() {
  const { documents, status, error, refresh } = useWorkspace();
  const { documentId } = useParams();
  const navigate = useNavigate();
  const [query, setQuery] = useState("");
  const [statusFilter, setStatusFilter] = useState("ALL");

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return documents.filter((d) => {
      if (statusFilter !== "ALL" && d.approval_status !== statusFilter) return false;
      if (!q) return true;
      return [String(d.id), d.title, d.document_type, d.workflow_title].some((v) => v.toLowerCase().includes(q));
    });
  }, [documents, query, statusFilter]);

  const selectedId = documentId ? Number(documentId) : null;
  const selected = selectedId !== null ? documents.find((d) => d.id === selectedId) : undefined;

  return (
    <>
      <PageHeader title="Documents" description="Documentation generated by the agents, with review status." />

      {status === "loading" ? (
        <Card>
          <TableSkeleton />
        </Card>
      ) : status === "error" ? (
        <Card>
          <ErrorState message={error ?? "Unable to load documents."} onRetry={() => void refresh()} />
        </Card>
      ) : documents.length === 0 ? (
        <Card>
          <EmptyState icon={FileText} title="No documents yet" description="Documents are created when the Documentation Agent completes a workflow." />
        </Card>
      ) : (
        <div className="grid gap-6 lg:grid-cols-[22rem_minmax(0,1fr)]">
          <Card className="flex max-h-[75vh] flex-col overflow-hidden">
            <div className="space-y-3 border-b border-slate-100 p-4">
              <SearchInput value={query} onChange={setQuery} placeholder="Search documents…" />
              <select
                aria-label="Filter by approval status"
                value={statusFilter}
                onChange={(e) => setStatusFilter(e.target.value)}
                className="w-full rounded-lg border border-slate-300 bg-white px-3 py-2 text-sm focus:border-brand-500 focus:outline-none focus:ring-2 focus:ring-brand-500/20"
              >
                <option value="ALL">All approval statuses</option>
                {APPROVAL_STATUSES.map((s) => (
                  <option key={s} value={s}>
                    {statusLabel(s)}
                  </option>
                ))}
              </select>
            </div>
            {filtered.length === 0 ? (
              <EmptyState title="No matching documents" />
            ) : (
              <ul className="divide-y divide-slate-100 overflow-y-auto">
                {filtered.map((d) => (
                  <DocumentListItem key={d.id} doc={d} selected={d.id === selectedId} onSelect={() => navigate(`/documents/${d.id}`)} />
                ))}
              </ul>
            )}
          </Card>

          <div className="min-w-0">
            {selected ? (
              <DocumentPane doc={selected} />
            ) : (
              <Card>
                <EmptyState
                  icon={FileText}
                  title={selectedId !== null ? "Document not found" : "Select a document"}
                  description={selectedId !== null ? `Document #${selectedId} is not in any loaded workflow.` : "Choose a document from the list to read its content."}
                />
              </Card>
            )}
          </div>
        </div>
      )}
    </>
  );
}
